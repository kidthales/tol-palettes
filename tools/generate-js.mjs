export function toIdent(id) {
  return id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
}

export function hexToRgb(hex) {
  if (typeof hex !== 'string' || !/^#[0-9A-Fa-f]{6}$/.test(hex)) {
    throw new TypeError(`Invalid #RRGGBB hex colour: ${hex}`);
  }
  return [
    Number.parseInt(hex.slice(1, 3), 16),
    Number.parseInt(hex.slice(3, 5), 16),
    Number.parseInt(hex.slice(5, 7), 16),
  ];
}

export function rgbToHex(r, g, b) {
  const clamp = (v) => Math.max(0, Math.min(255, Math.round(v)));
  const hex2 = (v) => clamp(v).toString(16).toUpperCase().padStart(2, '0');
  return `#${hex2(r)}${hex2(g)}${hex2(b)}`;
}

export function generateJsonBundle(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const map = {};
  for (const s of sorted) map[s.id] = s;
  return (
    JSON.stringify(
      {
        $comment: JSON_COMMENT,
        schemes: map,
      },
      null,
      2,
    ) + '\n'
  );
}

export function generateJsModule(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const constLines = sorted.map(
    (s) => `export const ${toIdent(s.id)} = ${JSON.stringify(s, null, 2)};`,
  );
  const mapEntries = sorted.map((s) => `  ${JSON.stringify(s.id)}: ${toIdent(s.id)},`);
  const listEntries = sorted.map((s) => `  ${toIdent(s.id)},`);

  return `${HEADER}
${constLines.join('\n\n')}

export const schemes = {
${mapEntries.join('\n')}
};

export const schemeList = [
${listEntries.join('\n')}
];

/**
 * Look up a scheme by its canonical id (returns undefined if unknown).
 * @param {string} id
 */
export function get(id) {
  return Object.prototype.hasOwnProperty.call(schemes, id) ? schemes[id] : undefined;
}

/**
 * Look up a scheme by id or return a passed scheme object; throws RangeError if unknown.
 * @param {string | object} schemeOrId
 */
export function getScheme(schemeOrId) {
  if (schemeOrId && typeof schemeOrId === 'object' && Array.isArray(schemeOrId.colors)) {
    return schemeOrId;
  }
  const s = get(String(schemeOrId));
  if (!s) throw new RangeError(\`Unknown Paul Tol scheme: \${schemeOrId}\`);
  return s;
}

/**
 * Parse a #RRGGBB hex string into [r, g, b] integers in 0..255.
 * @param {string} hex
 * @returns {[number, number, number]}
 */
export function hexToRgb(hex) {
  if (typeof hex !== 'string' || !/^#[0-9A-Fa-f]{6}$/.test(hex)) {
    throw new TypeError(\`Invalid #RRGGBB hex colour: \${hex}\`);
  }
  return [
    Number.parseInt(hex.slice(1, 3), 16),
    Number.parseInt(hex.slice(3, 5), 16),
    Number.parseInt(hex.slice(5, 7), 16),
  ];
}

/**
 * Format [r, g, b] integers (0..255) into an uppercase #RRGGBB hex string.
 * @param {number} r
 * @param {number} g
 * @param {number} b
 * @returns {string}
 */
export function rgbToHex(r, g, b) {
  const clamp = (v) => Math.max(0, Math.min(255, Math.round(v)));
  const hex2 = (v) => clamp(v).toString(16).toUpperCase().padStart(2, '0');
  return \`#\${hex2(r)}\${hex2(g)}\${hex2(b)}\`;
}

/**
 * Linearly interpolate a scheme in sRGB at position t in [0, 1].
 * Only allowed for schemes with interpolation: 'linear' | 'either'.
 * @param {string | object} schemeOrId
 * @param {number} t
 * @param {{ subrange?: string }} [options]
 * @returns {string}
 */
export function interpolate(schemeOrId, t, options = {}) {
  if (typeof t !== 'number' || !Number.isFinite(t)) {
    throw new TypeError(\`Expected a finite number t in [0, 1], got \${t}\`);
  }
  const scheme = getScheme(schemeOrId);
  if (scheme.interpolation === 'none') {
    throw new TypeError(\`Scheme "\${scheme.id}" does not support linear interpolation (interpolation: "none")\`);
  }
  let stops = scheme.colors;
  if (options && options.subrange) {
    const sub = (scheme.subranges ?? []).find((r) => r.id === options.subrange);
    if (!sub) {
      throw new RangeError(\`Unknown subrange "\${options.subrange}" for scheme "\${scheme.id}"\`);
    }
    stops = scheme.colors.slice(sub.from, sub.to + 1);
  }
  const clamped = Math.max(0, Math.min(1, t));
  const maxIndex = stops.length - 1;
  if (maxIndex === 0 || clamped === 0) return stops[0].hex;
  if (clamped === 1) return stops[maxIndex].hex;

  const pos = clamped * maxIndex;
  const lo = Math.floor(pos);
  const hi = Math.ceil(pos);
  if (lo === hi) return stops[lo].hex;

  const frac = pos - lo;
  const [r0, g0, b0] = hexToRgb(stops[lo].hex);
  const [r1, g1, b1] = hexToRgb(stops[hi].hex);
  return rgbToHex(r0 + frac * (r1 - r0), g0 + frac * (g1 - g0), b0 + frac * (b1 - b0));
}

/**
 * Sample \`count\` evenly spaced interpolated hex stops across [0, 1].
 * @param {string | object} schemeOrId
 * @param {number} count
 * @param {{ subrange?: string }} [options]
 * @returns {string[]}
 */
export function sample(schemeOrId, count, options = {}) {
  if (!Number.isInteger(count) || count < 1) {
    throw new RangeError(\`Sample count must be a positive integer, got \${count}\`);
  }
  if (count === 1) return [interpolate(schemeOrId, 0.5, options)];
  const out = [];
  for (let i = 0; i < count; i++) {
    out.push(interpolate(schemeOrId, i / (count - 1), options));
  }
  return out;
}

/**
 * Return the discrete rainbow palette of length n (1 <= n <= 23).
 * @param {number} n
 * @returns {string[]}
 */
export function discreteRainbow(n) {
  const lut = rainbowDiscrete.lut;
  if (!Number.isInteger(n) || n < 1 || n > lut.length) {
    throw new RangeError(\`discreteRainbow length must be an integer in 1..\${lut.length}, got \${n}\`);
  }
  return lut[n - 1].map((idx) => rainbowDiscrete.colors[idx].hex);
}

/**
 * Return the bad-data colour for discrete rainbow of length n (1 <= n <= 23).
 * @param {number} n
 * @returns {string}
 */
export function discreteRainbowBad(n) {
  const lut = rainbowDiscrete.lut;
  if (!Number.isInteger(n) || n < 1 || n > lut.length) {
    throw new RangeError(\`discreteRainbowBad length must be an integer in 1..\${lut.length}, got \${n}\`);
  }
  return rainbowDiscrete.lutBad?.[String(n)] ?? rainbowDiscrete.bad;
}

/**
 * Return the discrete hex colour list for a scheme.
 * - For rainbow-discrete, requires or uses n (defaults to max lut length 23).
 * - For schemes with discreteIndexes (e.g. nightfall), returns the indexed subset.
 * - Otherwise returns all defined stops in order.
 * @param {string | object} schemeOrId
 * @param {number} [n]
 * @returns {string[]}
 */
export function discreteColors(schemeOrId, n) {
  const scheme = getScheme(schemeOrId);
  if (scheme.lut) {
    const len = n === undefined ? scheme.lut.length : n;
    if (!Number.isInteger(len) || len < 1 || len > scheme.lut.length) {
      throw new RangeError(\`Length for "\${scheme.id}" must be an integer in 1..\${scheme.lut.length}, got \${len}\`);
    }
    return scheme.lut[len - 1].map((idx) => scheme.colors[idx].hex);
  }
  if (scheme.discreteIndexes) {
    return scheme.discreteIndexes.map((idx) => scheme.colors[idx].hex);
  }
  return scheme.colors.map((c) => c.hex);
}
`;
}

export function generateDts(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const idUnion = sorted.map((s) => JSON.stringify(s.id)).join(' | ');
  const constDecls = sorted.map((s) => `export declare const ${toIdent(s.id)}: Scheme;`).join('\n');

  return `${HEADER}
export type HexColor = \`#\${string}\`;
export type SchemeKind = 'qualitative' | 'diverging' | 'sequential' | 'special';
export type InterpolationMode = 'none' | 'linear' | 'either';
export type SchemeId = ${idUnion};

export interface SchemeColor {
  readonly hex: HexColor;
  readonly name?: string;
}

export interface SchemeSubrange {
  readonly id: string;
  readonly from: number;
  readonly to: number;
  readonly bad?: HexColor;
}

export interface SchemeSource {
  readonly retrieved: string;
  readonly siteFigure?: string;
  readonly siteUrl?: string;
  readonly module?: string;
  readonly moduleName?: string;
  readonly moduleVersion?: string;
  readonly notes?: readonly string[];
}

export interface Scheme {
  readonly id: SchemeId;
  readonly kind: SchemeKind;
  readonly colors: readonly SchemeColor[];
  readonly extras?: readonly SchemeColor[];
  readonly bad?: HexColor;
  readonly interpolation: InterpolationMode;
  readonly discreteIndexes?: readonly number[];
  readonly lut?: readonly (readonly number[])[];
  readonly lutBad?: Readonly<Record<string, HexColor>>;
  readonly subranges?: readonly SchemeSubrange[];
  readonly source: SchemeSource;
}

${constDecls}

export declare const schemes: Readonly<Record<SchemeId, Scheme>>;
export declare const schemeList: readonly Scheme[];

export declare function get(id: SchemeId): Scheme;
export declare function get(id: string): Scheme | undefined;
export declare function getScheme(schemeOrId: Scheme | SchemeId | string): Scheme;
export declare function hexToRgb(hex: string): [number, number, number];
export declare function rgbToHex(r: number, g: number, b: number): HexColor;
export declare function interpolate(
  schemeOrId: Scheme | SchemeId | string,
  t: number,
  options?: { subrange?: string },
): HexColor;
export declare function sample(
  schemeOrId: Scheme | SchemeId | string,
  count: number,
  options?: { subrange?: string },
): HexColor[];
export declare function discreteRainbow(n: number): HexColor[];
export declare function discreteRainbowBad(n: number): HexColor;
export declare function discreteColors(schemeOrId: Scheme | SchemeId | string, n?: number): HexColor[];
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const schemes = loadSchemes().map((x) => x.data);
  const jsonDir = join(root, 'dist', 'json');
  const jsDir = join(root, 'dist', 'js');
  rmSync(jsonDir, { recursive: true, force: true });
  rmSync(jsDir, { recursive: true, force: true });
  mkdirSync(jsonDir, { recursive: true });
  mkdirSync(jsDir, { recursive: true });

  writeFileSync(join(jsonDir, 'schemes.json'), generateJsonBundle(schemes));
  writeFileSync(join(jsDir, 'index.js'), generateJsModule(schemes));
  writeFileSync(join(jsDir, 'index.d.ts'), generateDts(schemes));
  console.log('Wrote dist/json/schemes.json, dist/js/index.js and dist/js/index.d.ts.');
}

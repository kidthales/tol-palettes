// Generates CSS custom properties for every scheme into dist/css/.
//   dist/css/<id>.css   one file per scheme
//   dist/css/tol.css    bundle of all schemes
//
// Property naming (documented in docs/css.md):
//   --tol-<id>-<index>           colour at data index (0-based, same indexes as lut/subranges)
//   --tol-<id>-<name>            only when the official module provides a name
//   --tol-<id>-bad               bad-data colour when the source gives one
//   --tol-<id>-gradient          linear-gradient for schemes meant to be interpolated
//   --tol-<id>-discrete-<k>      discrete variant when it differs (discreteIndexes)
//   --tol-<id>-n<N>-<k>          discrete rainbow lookup: N requested colours, k-th colour
import { mkdirSync, writeFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSchemes } from './validate.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const HEADER = `/*
 * Colour values from Paul Tol's colour schemes (https://sronpersonalpages.nl/~pault/),
 * with the 3-clause BSD notice for values derived from tol_colors.py. See NOTICE.
 * Independent project: not affiliated with or endorsed by Paul Tol.
 * Generated by tools/generate-css.mjs from data/schemes/*.json. Do not edit by hand.
 */
`;

/** Returns [propertyName, value] pairs for one scheme, in a stable order. */
export function properties(s) {
  const p = `--tol-${s.id}`;
  const out = [];
  s.colors.forEach((c, i) => out.push([`${p}-${i}`, c.hex]));
  s.colors.forEach((c) => c.name && out.push([`${p}-${c.name}`, c.hex]));
  (s.extras ?? []).forEach((c) => c.name && out.push([`${p}-${c.name}`, c.hex]));
  if (s.bad) out.push([`${p}-bad`, s.bad]);
  if (s.interpolation !== 'none') {
    out.push([`${p}-gradient`, `linear-gradient(in srgb to right, ${s.colors.map((c) => c.hex).join(', ')})`]);
  }
  if (s.discreteIndexes) s.discreteIndexes.forEach((idx, k) => out.push([`${p}-discrete-${k}`, s.colors[idx].hex]));
  if (s.lut) {
    s.lut.forEach((row, n) => row.forEach((idx, k) => out.push([`${p}-n${n + 1}-${k}`, s.colors[idx].hex])));
  }
  return out;
}

export function cssFor(s) {
  const lines = properties(s).map(([k, v]) => `  ${k}: ${v};`);
  return `/* ${s.id} (${s.kind}) */\n:root {\n${lines.join('\n')}\n}\n`;
}

export function generateAll(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const files = new Map();
  for (const s of sorted) files.set(`${s.id}.css`, HEADER + '\n' + cssFor(s));
  files.set('tol.css', HEADER + '\n' + sorted.map(cssFor).join('\n'));
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dir = join(root, 'dist', 'css');
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  const files = generateAll();
  for (const [name, text] of files) writeFileSync(join(dir, name), text);
  console.log(`Wrote ${files.size} files to dist/css (${readdirSync(dir).length} entries).`);
}

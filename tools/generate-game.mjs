// Generates game and pixel-art palette outputs from data/schemes/*.json:
//   dist/gpl/<id>.gpl          GIMP / Aseprite / Inkscape / Krita palette files
//   dist/aseprite/<id>.gpl     Aseprite palette files (with Aseprite header comments)
//   dist/godot/tol_palettes.gd GDScript 2.0 (Godot 4.x) constants & helper class
//   dist/godot/<id>.tres       Godot 4.x ColorPalette resources for the editor ColorPicker
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSchemes } from './validate.mjs';
import { hexToRgb } from './generate-js.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const COMMENT_LINES = [
  "Colour values from Paul Tol's colour schemes (https://sronpersonalpages.nl/~pault/),",
  'with the 3-clause BSD notice for values derived from tol_colors.py. See NOTICE.',
  'Independent project: not affiliated with or endorsed by Paul Tol.',
  'Generated by tools/generate-game.mjs from data/schemes/*.json. Do not edit by hand.',
];

function schemeAllColors(scheme) {
  return [...scheme.colors, ...(scheme.extras ?? [])];
}

export function gplFor(scheme, { aseprite = false } = {}) {
  const all = schemeAllColors(scheme);
  const cols = Math.min(all.length, 16);
  const header = [
    'GIMP Palette',
    `Name: tol-${scheme.id}`,
    `Columns: ${cols}`,
    ...(aseprite ? ['# Aseprite-compatible GIMP Palette (.gpl)'] : []),
    ...COMMENT_LINES.map((l) => `# ${l}`),
    '#',
  ];
  const rows = all.map((c) => {
    const [r, g, b] = hexToRgb(c.hex);
    const rPad = String(r).padStart(3, ' ');
    const gPad = String(g).padStart(3, ' ');
    const bPad = String(b).padStart(3, ' ');
    // Only emit a colour name when the official source provides one; otherwise emit the hex code.
    const label = c.name ? c.name : c.hex;
    return `${rPad} ${gPad} ${bPad}\t${label}`;
  });
  return [...header, ...rows, ''].join('\n');
}

function gdConstName(schemeId, colorName) {
  return `${schemeId}_${colorName}`.toUpperCase().replace(/[^A-Z0-9]+/g, '_');
}

function hexToFloatTriplet(hex) {
  const [r, g, b] = hexToRgb(hex);
  const fmt = (n) => Number((n / 255).toFixed(6));
  return `${fmt(r)}, ${fmt(g)}, ${fmt(b)}, 1`;
}

export function godotTresFor(scheme) {
  const all = schemeAllColors(scheme);
  const floats = all.map((c) => hexToFloatTriplet(c.hex)).join(', ');
  const comments = COMMENT_LINES.map((l) => `; ${l}`).join('\n');
  return `[gd_resource type="ColorPalette" format=3]\n\n${comments}\n; Scheme: ${scheme.id} (${scheme.kind})\n\n[resource]\ncolors = PackedColorArray(${floats})\n`;
}

export function generateGodotScript(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const header = COMMENT_LINES.map((l) => `# ${l}`).join('\n');

  const namedConsts = [];
  for (const s of sorted) {
    const all = schemeAllColors(s);
    for (const c of all) {
      if (c.name) {
        namedConsts.push(`const ${gdConstName(s.id, c.name)} := Color("${c.hex}")`);
      }
    }
  }

  const schemeEntries = sorted.map((s) => {
    const primaryColors = s.colors.map((c) => `Color("${c.hex}")`).join(', ');
    const primaryHex = s.colors.map((c) => `"${c.hex}"`).join(', ');
    const all = schemeAllColors(s);
    const namedPairs = all.filter((c) => c.name).map((c) => `"${c.name}": Color("${c.hex}")`);
    const lines = [
      `\t"${s.id}": {`,
      `\t\t"id": "${s.id}",`,
      `\t\t"kind": "${s.kind}",`,
      `\t\t"interpolation": "${s.interpolation}",`,
      `\t\t"colors": PackedColorArray([${primaryColors}]),`,
      `\t\t"hex": PackedStringArray([${primaryHex}]),`,
    ];
    if (s.extras && s.extras.length > 0) {
      const extraColors = s.extras.map((c) => `Color("${c.hex}")`).join(', ');
      lines.push(`\t\t"extras": PackedColorArray([${extraColors}]),`);
    }
    if (s.bad) {
      lines.push(`\t\t"bad": Color("${s.bad}"),`);
    }
    if (namedPairs.length > 0) {
      lines.push(`\t\t"named": { ${namedPairs.join(', ')} },`);
    }
    if (s.discreteIndexes) {
      lines.push(`\t\t"discrete_indexes": [${s.discreteIndexes.join(', ')}],`);
    }
    lines.push('\t},');
    return lines.join('\n');
  });

  const rd = sorted.find((s) => s.id === 'rainbow-discrete');
  const lutRows = rd.lut.map((row) => `\t[${row.join(', ')}],`).join('\n');

  return `@tool
class_name TolPalettes
extends RefCounted
${header}

${namedConsts.join('\n')}

const SCHEMES: Dictionary = {
${schemeEntries.join('\n')}
}

const RAINBOW_DISCRETE_LUT: Array = [
${lutRows}
]


static func get_colors(scheme_id: String) -> PackedColorArray:
\tassert(SCHEMES.has(scheme_id), "Unknown Paul Tol scheme: " + scheme_id)
\treturn SCHEMES[scheme_id]["colors"]


static func get_hex(scheme_id: String) -> PackedStringArray:
\tassert(SCHEMES.has(scheme_id), "Unknown Paul Tol scheme: " + scheme_id)
\treturn SCHEMES[scheme_id]["hex"]


static func get_named(scheme_id: String, color_name: String) -> Color:
\tassert(SCHEMES.has(scheme_id), "Unknown Paul Tol scheme: " + scheme_id)
\tvar scheme: Dictionary = SCHEMES[scheme_id]
\tassert(scheme.has("named") and scheme["named"].has(color_name), "Unknown named colour: " + scheme_id + "." + color_name)
\treturn scheme["named"][color_name]


static func get_discrete_rainbow(n: int) -> PackedColorArray:
\tassert(n >= 1 and n <= RAINBOW_DISCRETE_LUT.size(), "rainbow-discrete length must be in 1..23")
\tvar base: PackedColorArray = SCHEMES["rainbow-discrete"]["colors"]
\tvar idxs: Array = RAINBOW_DISCRETE_LUT[n - 1]
\tvar out := PackedColorArray()
\tfor idx in idxs:
\t\tout.append(base[idx])
\treturn out
`;
}

export function generateAllGame(schemes = loadSchemes().map((x) => x.data)) {
  const sorted = [...schemes].sort((a, b) => a.id.localeCompare(b.id));
  const gplFiles = new Map();
  const aseFiles = new Map();
  const godotFiles = new Map();

  for (const s of sorted) {
    gplFiles.set(`${s.id}.gpl`, gplFor(s, { aseprite: false }));
    aseFiles.set(`${s.id}.gpl`, gplFor(s, { aseprite: true }));
    godotFiles.set(`${s.id}.tres`, godotTresFor(s));
  }
  godotFiles.set('tol_palettes.gd', generateGodotScript(sorted));
  return { gplFiles, aseFiles, godotFiles };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { gplFiles, aseFiles, godotFiles } = generateAllGame();
  const gplDir = join(root, 'dist', 'gpl');
  const aseDir = join(root, 'dist', 'aseprite');
  const godotDir = join(root, 'dist', 'godot');

  for (const dir of [gplDir, aseDir, godotDir]) {
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
  }

  for (const [name, text] of gplFiles) writeFileSync(join(gplDir, name), text);
  for (const [name, text] of aseFiles) writeFileSync(join(aseDir, name), text);
  for (const [name, text] of godotFiles) writeFileSync(join(godotDir, name), text);

  console.log(
    `Wrote ${gplFiles.size} files to dist/gpl, ${aseFiles.size} to dist/aseprite and ${godotFiles.size} to dist/godot.`,
  );
}
